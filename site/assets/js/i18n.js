/* ---------- helpers ---------- */
(function () {
  var current = 'en';

  window.rfbLang = function () { return current; };

  /* Each language version has its own shareable URL (?lang=en / ?lang=pt).
     An explicit parameter always wins over the stored preference. */
  function langFromUrl() {
    try {
      var m = /[?&]lang=(pt|en)\b/.exec(window.location.search || '');
      return m ? m[1] : null;
    } catch (e) { return null; }
  }

  function writeLangToUrl(lang) {
    try {
      if (!window.history || !window.history.replaceState) return;
      var url = new URL(window.location.href);
      url.searchParams.set('lang', lang);
      window.history.replaceState({}, '', url.toString());
    } catch (e) { /* noop */ }
  }

  window.rfbInitialLang = function () {
    var fromUrl = langFromUrl();
    if (fromUrl) return fromUrl;
    var saved = null;
    try { saved = localStorage.getItem('rfb-lang'); } catch (e) { /* private mode */ }
    if (saved === 'pt' || saved === 'en') return saved;
    return 'en'; // English is the default; Portuguese is available via the switch or ?lang=pt.
  };

  window.t = function (key, vars) {
    var dict = window.I18N[current] || {};
    var s = dict[key];
    if (s === undefined) s = (window.I18N.en || {})[key];
    if (s === undefined) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  };

  window.applyI18n = function (lang, keepUrl) {
    current = (lang === 'en') ? 'en' : 'pt';
    try { localStorage.setItem('rfb-lang', current); } catch (e) { /* private mode */ }
    document.documentElement.lang = (current === 'en') ? 'en' : 'pt-BR';
    if (!keepUrl) writeLangToUrl(current);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = window.t(el.getAttribute('data-i18n'));
      if (el.innerHTML !== v) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      // format: "attr:key,attr:key"
      el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
        var p = pair.split(':');
        if (p.length === 2) el.setAttribute(p[0], window.t(p[1].trim()));
      });
    });
    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      b.classList.toggle('is-active', b.getAttribute('data-lang') === current);
    });

    /* the document identity follows the language too */
    var dt = window.t('meta.docTitle');
    if (dt && dt !== 'meta.docTitle' && document.title !== dt) document.title = dt;
    var dm = document.querySelector('meta[name="description"]');
    var dd = window.t('meta.docDesc');
    if (dm && dd && dd !== 'meta.docDesc') dm.setAttribute('content', dd);

    if (window.rfbOnLanguageChange) window.rfbOnLanguageChange(current);
  };

  window.tpl = function (key, vars) {
    var s = window.t(key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  };
})();
